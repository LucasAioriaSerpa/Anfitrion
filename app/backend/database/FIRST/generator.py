"""Generate Database First artifacts from the existing SQLite database.

Usage:
    py -m app.backend.database.FIRST.generator
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

try:
    from .schema import introspect_database, write_schema
except ImportError:
    from schema import introspect_database, write_schema


ROOT = Path(__file__).resolve().parents[3]
DATABASE_PATH = ROOT / "database" / "db_anfitrion.db"
OUTPUT_DIR = Path(__file__).resolve().parent / "generated"
HEADER = "# AUTO-GENERATED by app/backend/database/FIRST/generator.py. DO NOT EDIT.\n"


def _model_source(schema: dict) -> str:
    lines = [HEADER, "from dataclasses import dataclass\nfrom typing import Any\n\n"]
    for table in schema["tables"]:
        lines.append("@dataclass\n")
        lines.append(f"class {table['class_name']}:\n")
        for column in table["columns"]:
            annotation = column["python_type"]
            if column["nullable"] or column["default"] is not None:
                annotation = f"{annotation} | None"
            lines.append(f"    {column['name']}: {annotation} = None\n")
        lines.append("\n")
    return "".join(lines)


def _repository_source() -> str:
    return HEADER + '''from __future__ import annotations

import json
from pathlib import Path
from typing import Any

try:
    from app.backend.manager.Database import Database
except ImportError:
    from manager.Database import Database

SCHEMA_PATH = Path(__file__).with_name("schema.json")
SENSITIVE_FIELDS = {"senha", "password", "token", "secret"}


def load_schema() -> dict[str, Any]:
    return json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))


class GeneratedRepository:
    """Generic CRUD repository constrained by the generated schema."""

    def __init__(self, table: dict[str, Any]):
        self.table = table
        self.database = Database()
        self.columns = {column["name"]: column for column in table["columns"]}
        self.primary_key = table["primary_key"]

    def public_columns(self) -> list[str]:
        return [
            name for name, column in self.columns.items()
            if name not in SENSITIVE_FIELDS and not column["primary_key"]
        ]

    def _safe_payload(self, payload: dict[str, Any]) -> dict[str, Any]:
        allowed = set(self.public_columns())
        return {key: value for key, value in payload.items() if key in allowed}

    def list(self, filters: dict[str, Any] | None = None) -> list[dict[str, Any]]:
        safe_filters = {
            key: value for key, value in (filters or {}).items()
            if key in self.columns and key not in SENSITIVE_FIELDS
        }
        return self.database.read(self.table["name"], safe_filters)

    def get(self, identifier: int) -> list[dict[str, Any]]:
        return self.database.read(self.table["name"], {self.primary_key: identifier})

    def create(self, payload: dict[str, Any]) -> int:
        data = self._safe_payload(payload)
        if not data:
            raise ValueError("Nenhum campo público foi informado")
        return self.database.create(self.table["name"], data)

    def update(self, identifier: int, payload: dict[str, Any]) -> bool:
        data = self._safe_payload(payload)
        if not data:
            raise ValueError("Nenhum campo público foi informado")
        return self.database.update(self.table["name"], data, {self.primary_key: identifier})

    def delete(self, identifier: int) -> bool:
        return self.database.delete(self.table["name"], {self.primary_key: identifier})
'''


def _routes_source() -> str:
    return HEADER + '''from __future__ import annotations

from functools import wraps

from flask import Blueprint, jsonify, request

try:
    from app.backend.api.auth.auth_context import current_user, require_auth
except ImportError:
    from api.auth.auth_context import current_user, require_auth
try:
    from app.backend.manager.Database import Database
except ImportError:
    from manager.Database import Database

from .repository import GeneratedRepository, load_schema

generated_bp = Blueprint("database_first", __name__, url_prefix="/api/generated")
SCHEMA = load_schema()
TABLES = {table["name"]: table for table in SCHEMA["tables"]}
database = Database()


def require_admin(view):
    @wraps(view)
    @require_auth
    def wrapped(*args, **kwargs):
        user = current_user()
        cargo = str(user.get("cargo", ""))
        if not cargo and user.get("id_funcionario"):
            funcionarios = database.read("funcionario", {"id_funcionario": user["id_funcionario"]})
            cargo = str(funcionarios[0].get("cargo", "")) if funcionarios else ""
        if user.get("role") != "funcionario" or "admin" not in cargo.lower():
            return _error("Apenas administradores podem usar o CRUD gerado", 403)
        return view(*args, **kwargs)
    return wrapped


def _repository(resource: str) -> GeneratedRepository:
    table = TABLES.get(resource)
    if table is None or not table.get("generated_resource", True):
        raise KeyError(resource)
    return GeneratedRepository(table)


def _error(message: str, status: int):
    return jsonify({"success": False, "status": status, "message": message, "data": None}), status


@generated_bp.get("/schema")
@require_admin
def schema():
    public_schema = []
    for table in SCHEMA["tables"]:
        public_schema.append({
            "name": table["name"],
            "class_name": table["class_name"],
            "primary_key": table["primary_key"],
            "columns": [
                column for column in table["columns"]
                if column["name"] not in {"senha", "password", "token", "secret"}
            ],
        })
    return jsonify({"success": True, "status": 200, "data": public_schema}), 200


@generated_bp.get("")
@generated_bp.get("/")
@require_admin
def generated_root():
    return jsonify({
        "success": True,
        "status": 200,
        "message": "Database First CRUD disponível",
        "resources": [
            {
                "name": table["name"],
                "url": f"/api/generated/{table['name']}",
                "schema_url": "/api/generated/schema",
            }
            for table in SCHEMA["tables"]
            if table.get("generated_resource", True)
        ],
    }), 200


@generated_bp.get("/<resource>")
@require_admin
def list_resource(resource: str):
    try:
        records = _repository(resource).list(request.args.to_dict())
    except KeyError:
        return _error("Recurso não encontrado", 404)
    return jsonify({"success": True, "status": 200, "data": records}), 200


@generated_bp.get("/<resource>/<int:identifier>")
@require_admin
def get_resource(resource: str, identifier: int):
    try:
        records = _repository(resource).get(identifier)
    except KeyError:
        return _error("Recurso não encontrado", 404)
    if not records:
        return _error("Registro não encontrado", 404)
    return jsonify({"success": True, "status": 200, "data": records[0]}), 200


@generated_bp.post("/<resource>")
@require_admin
def create_resource(resource: str):
    try:
        identifier = _repository(resource).create(request.get_json(silent=True) or {})
    except KeyError:
        return _error("Recurso não encontrado", 404)
    except (ValueError, TypeError) as error:
        return _error(str(error), 400)
    except Exception:
        return _error("Não foi possível criar o registro", 409)
    return jsonify({"success": True, "status": 201, "data": {"id": identifier}}), 201


@generated_bp.put("/<resource>/<int:identifier>")
@require_admin
def update_resource(resource: str, identifier: int):
    try:
        repository = _repository(resource)
        if not repository.get(identifier):
            return _error("Registro não encontrado", 404)
        repository.update(identifier, request.get_json(silent=True) or {})
    except KeyError:
        return _error("Recurso não encontrado", 404)
    except (ValueError, TypeError) as error:
        return _error(str(error), 400)
    except Exception:
        return _error("Não foi possível atualizar o registro", 409)
    return jsonify({"success": True, "status": 200, "data": {"id": identifier}}), 200


@generated_bp.delete("/<resource>/<int:identifier>")
@require_admin
def delete_resource(resource: str, identifier: int):
    try:
        repository = _repository(resource)
        if not repository.get(identifier):
            return _error("Registro não encontrado", 404)
        repository.delete(identifier)
    except KeyError:
        return _error("Recurso não encontrado", 404)
    except Exception:
        return _error("Não foi possível excluir o registro", 409)
    return jsonify({"success": True, "status": 200, "data": {"id": identifier}}), 200
'''


def generate(database_path: Path = DATABASE_PATH, output_dir: Path = OUTPUT_DIR) -> dict:
    schema = introspect_database(database_path)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "__init__.py").write_text(HEADER + "from .routes import generated_bp\n", encoding="utf-8")
    write_schema(database_path, output_dir / "schema.json")
    (output_dir / "models.py").write_text(_model_source(schema), encoding="utf-8")
    (output_dir / "repository.py").write_text(_repository_source(), encoding="utf-8")
    (output_dir / "routes.py").write_text(_routes_source(), encoding="utf-8")
    return schema


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Database First artifacts from SQLite")
    parser.add_argument("--database", type=Path, default=DATABASE_PATH)
    parser.add_argument("--output", type=Path, default=OUTPUT_DIR)
    args = parser.parse_args()
    schema = generate(args.database, args.output)
    print(f"Generated {len(schema['tables'])} tables in {args.output}")


if __name__ == "__main__":
    main()
